/**
 * Fetch the two webfonts Palace UI ships and inline them as base64 @font-face
 * rules. DSH serves plain client plugins without a package asset route, so the
 * font bytes travel inside the stylesheet (CJK still uses the platform stack).
 *
 *   node scripts/fetch-fonts.mjs
 *
 * Source: Google Fonts (Inter and JetBrains Mono, both OFL). The latin subsets
 * keep the payload small; `unicode-range` keeps CJK on the system fallback.
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const fontDir = path.join(root, 'assets', 'fonts');
const outCss = path.join(root, 'styles', '05-fonts.css');

const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';
const FAMILIES = [
  { query: 'Inter:wght@100..900', id: 'inter', weights: '100 900', style: 'normal' },
  { query: 'JetBrains+Mono:wght@100..800', id: 'jetbrains-mono', weights: '100 800', style: 'normal' },
];

const LATIN_RANGE =
  'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';

async function get(url) {
  const res = await fetch(url, { headers: { 'user-agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res;
}

async function main() {
  fs.mkdirSync(fontDir, { recursive: true });
  const blocks = [];
  for (const family of FAMILIES) {
    const cssUrl = `https://fonts.googleapis.com/css2?family=${family.query}&display=swap`;
    const css = await (await get(cssUrl)).text();
    // Keep only the latin subset @font-face (the last block of each family).
    const blocksRaw = css.split('@font-face').slice(1);
    const latin = blocksRaw.filter((b) => /unicode-range:\s*U\+0000-00FF/.test(b)).pop();
    if (!latin) throw new Error(`no latin subset for ${family.id}`);
    const url = /url\((https:[^)]+\.woff2)\)/.exec(latin);
    if (!url) throw new Error(`no woff2 url for ${family.id}`);
    const buf = Buffer.from(await (await get(url[1])).arrayBuffer());
    const file = path.join(fontDir, `${family.id}-latin.woff2`);
    fs.writeFileSync(file, buf);
    const b64 = buf.toString('base64');
    console.log(`${family.id}: ${(buf.length / 1024).toFixed(1)} KiB`);
    blocks.push(
      `@font-face {\n  font-family: '${family.id === 'inter' ? 'Inter' : 'JetBrains Mono'}';\n  font-style: ${family.style};\n  font-weight: ${family.weights};\n  font-display: swap;\n  src: url(data:font/woff2;base64,${b64}) format('woff2');\n  unicode-range: ${LATIN_RANGE};\n}`,
    );
  }
  const css = `/* =====================================================================
 * palace-ui / 05 · Bundled webfonts (generated by scripts/fetch-fonts.mjs)
 * =====================================================================
 * Inter + JetBrains Mono (SIL Open Font License), latin subsets only. CJK
 * falls through to the platform stack declared in 00-tokens.css.
 * ===================================================================== */
${blocks.join('\n\n')}
`;
  fs.writeFileSync(outCss, css);
  console.log(`wrote ${(Buffer.byteLength(css) / 1024).toFixed(1)} KiB -> ${outCss}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
